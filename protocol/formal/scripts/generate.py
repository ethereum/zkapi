def scaled_form(st):
    lam, lams, rounds = 1, [1], []
    for (k, a, b, cc, w1, w2) in st["partial"]:
        require(a != 0, "zero leading coefficient")
        l5 = pow(lam, 5, P)
        nl = a * l5 % P
        rounds.append([k * inv(lam) % P, b * inv(nl) % P, cc * inv(nl) % P, w1 * l5 % P, w2 * l5 % P])
        lam = nl
        lams.append(lam)
    k = st["last_k"]
    l5 = pow(lam, 5, P)
    lk = [k[0] * inv(lam) % P, k[1], k[2]]
    lm = [[st["last_m"][i][0] * l5 % P, st["last_m"][i][1], st["last_m"][i][2]] for i in range(3)]
    require(len(lams) == RP, "scaling factor count")
    # The multiplicative identities the Lean proof checks (ZkapiFormal/Poseidon/Scaled.lean).
    for j, ((k, a, b, cc, w1, w2), (sk, sb, sc, sw1, sw2)) in enumerate(zip(st["partial"], rounds)):
        l, nl = lams[j], lams[j + 1]
        require(nl == a * pow(l, 5, P) % P and k == l * sk % P and b == nl * sb % P
                and cc == nl * sc % P and sw1 == w1 * pow(l, 5, P) % P
                and sw2 == w2 * pow(l, 5, P) % P, f"scaled round {j}")
    return dict(full=st["full"], partial=rounds, last_k=lk, last_m=lm, lam=lams)


def permute_scaled(sc, mds, s):
    s = list(s)
    for k in sc["full"][:RF_HALF]:
        s = mat_vec(mds, [pow5((s[i] + k[i]) % P) for i in range(3)])
    for (k, b, cc, w1, w2) in sc["partial"]:
        y = pow5((s[0] + k) % P)
        s = [(y + b * s[1] + cc * s[2]) % P, (s[1] + w1 * y) % P, (s[2] + w2 * y) % P]
    k = sc["last_k"]
    s = mat_vec(sc["last_m"], [pow5((s[0] + k[0]) % P), (s[1] + k[1]) % P, (s[2] + k[2]) % P])
    for k in sc["full"][RF_HALF:]:
        s = mat_vec(mds, [pow5((s[i] + k[i]) % P) for i in range(3)])
    return s


