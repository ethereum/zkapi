PERMUTE_HEAD = "            function permute(s0, s1, s2) -> r0, r1, r2 {\n"
PERMUTE_TAIL = "                r0 := s0\n                r1 := s1\n                r2 := s2\n            }\n"


def permute_body_of(src, label):
    """The text of the runtime's `permute` body (between its header line and its three returns),
    after requiring that the function appears once, at its place, and ends with exactly the
    returns `r0 := s0  r1 := s1  r2 := s2`."""
    require(src.count(PERMUTE_HEAD) == 1, "%s: `function permute(s0, s1, s2) -> r0, r1, r2 {` once" % label)
    start = src.index(PERMUTE_HEAD) + len(PERMUTE_HEAD)
    end = src.find(PERMUTE_TAIL, start)
    require(end >= 0, "%s: permute does not end with its three returns" % label)
    return src[start:end]


