def sparse_form(ark, mds):
    c = [list(r) for r in ark]
    first, last = RF_HALF, RF_HALF + RP - 1
    for r in range(first, last + 1):
        d = mat_vec(mds, [0, c[r][1], c[r][2]])
        c[r] = [c[r][0], 0, 0]
        for i in range(3):
            c[r + 1][i] = (c[r + 1][i] + d[i]) % P
    words = []
    for rnd in c[:RF_HALF]:
        words += rnd
    l = [row[:] for row in mds]
    partial, basis = [], [[[1, 0, 0], [0, 1, 0], [0, 0, 1]]]
    dense = [l]
    for rnd in c[first:last]:
        det = (l[1][1] * l[2][2] - l[1][2] * l[2][1]) % P
        di = inv(det)
        sub = [[l[2][2] * di % P, -l[1][2] * di % P], [-l[2][1] * di % P, l[1][1] * di % P]]
        w = [(sub[0][0] * l[1][0] + sub[0][1] * l[2][0]) % P,
             (sub[1][0] * l[1][0] + sub[1][1] * l[2][0]) % P]
        words.append(rnd[0])
        words += l[0]
        words += w
        partial.append([rnd[0], l[0][0], l[0][1], l[0][2], w[0], w[1]])
        mp = [[1, 0, 0], [0, l[1][1], l[1][2]], [0, l[2][1], l[2][2]]]
        basis.append(mp)
        l = mat_mul(mds, mp)
        dense.append(l)
    words += c[last]
    for row in l:
        words += row
    for rnd in c[RF_HALF + RP:]:
        words += rnd
    require(len(words) == 372, "sparse word count")
    st = dict(full=c[:RF_HALF] + c[RF_HALF + RP:], partial=partial, last_k=c[last][:],
              last_m=[row[:] for row in l], basis=basis, words=words)
    require(st["last_k"][1] == 0 and st["last_k"][2] == 0, "last partial round constants")
    # Certificates for the Lean proof (ZkapiFormal/Poseidon/Sparse.lean): with B_j = basis[j]
    # and tau_j below, the reference state before round 4+j is B_j u_j + tau_j, where u_j is the
    # sparse state before its partial round j.
    tau = [[0, 0, 0]]
    for j in range(RP - 1):
        k = partial[j][0]
        rho = [(tau[j][i] + ark[4 + j][i] - (k if i == 0 else 0)) % P for i in range(3)]
        require(rho[0] == 0, f"partial constant {j} is not the lane-0 pre-S-box constant")
        tau.append(mat_vec(mds, rho))
        a, b, cc, w1, w2 = partial[j][1:]
        sparse_mat = [[a, b, cc], [w1, 1, 0], [w2, 0, 1]]
        require(mat_mul(mds, basis[j]) == mat_mul(basis[j + 1], sparse_mat), f"factor {j}")
    k = st["last_k"][0]
    rho = [(tau[RP - 1][i] + ark[RF_HALF + RP - 1][i] - (k if i == 0 else 0)) % P for i in range(3)]
    require(rho[0] == 0, "last partial constant")
    require(mat_mul(mds, basis[RP - 1]) == st["last_m"], "last dense matrix")
    lk_rest = [0, st["last_k"][1], st["last_k"][2]]
    t57 = [(x - y) % P for x, y in zip(mat_vec(mds, rho), mat_vec(st["last_m"], lk_rest))]
    tau.append(t57)
    require([(t57[i] + ark[RF_HALF + RP][i]) % P for i in range(3)] == st["full"][RF_HALF],
            "relocated constants of the first suffix round")
    st["translation"] = tau
    return st


def permute_sparse(st, mds, s):
    s = list(s)
    for k in st["full"][:RF_HALF]:
        s = mat_vec(mds, [pow5((s[i] + k[i]) % P) for i in range(3)])
    for (k, a, b, cc, w1, w2) in st["partial"]:
        x = pow5((s[0] + k) % P)
        s = [(a * x + b * s[1] + cc * s[2]) % P, (s[1] + w1 * x) % P, (s[2] + w2 * x) % P]
    k = st["last_k"]
    s = mat_vec(st["last_m"], [pow5((s[0] + k[0]) % P), (s[1] + k[1]) % P, (s[2] + k[2]) % P])
    for k in st["full"][RF_HALF:]:
        s = mat_vec(mds, [pow5((s[i] + k[i]) % P) for i in range(3)])
    return s


def deployed_blob():
    src = REFERENCE_SOL.read_text()
    m = re.search(r"bytes internal constant CONSTANTS =\s*((?:hex\"[0-9a-fA-F]*\"\s*)+);", src)
    require(m is not None, "CONSTANTS blob not found in Bn254PoseidonReference.sol")
    hexs = "".join(re.findall(r'hex"([0-9a-fA-F]*)"', m.group(1)))
    require(len(hexs) % 64 == 0, "CONSTANTS blob length")
    return [int(hexs[64 * i:64 * i + 64], 16) for i in range(len(hexs) // 64)]


