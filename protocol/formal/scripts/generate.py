def inv(a):
    require(a % P != 0, "inverse of zero")
    return pow(a, P - 2, P)


def mat_vec(a, v):
    return [sum(a[i][j] * v[j] for j in range(3)) % P for i in range(3)]


def mat_mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) % P for j in range(3)] for i in range(3)]


def pow5(x):
    return pow(x, 5, P)


