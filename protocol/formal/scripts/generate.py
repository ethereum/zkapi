YUL_LEX = re.compile(r"\s+|//[^\n]*|->|0x[0-9a-fA-F]+|[0-9]+|[A-Za-z_][A-Za-z0-9_]*|:=|[{}(),]")
# Yul keywords the Lean grammar (ZkapiFormal/Yul/Syntax.lean) leaves out; a source using them is
# rejected.
YUL_KEYWORDS = {"leave", "break", "continue", "true", "false", "hex"}
PUNCT = {"{": ".lb", "}": ".rb", "(": ".lp", ")": ".rp", ",": ".comma", ":=": ".assign",
         "->": ".arrow", "let": ".kwLet", "if": ".kwIf", "function": ".kwFunction",
         "switch": ".kwSwitch", "case": ".kwCase", "default": ".kwDefault", "for": ".kwFor"}


def lex_yul(text):
    """Split Yul source into tokens. Every character is consumed by exactly one alternative of
    YUL_LEX; only whitespace and `//` comments are dropped, so the tokens are the source."""
    out, i = [], 0
    while i < len(text):
        m = YUL_LEX.match(text, i)
        require(m is not None and m.end() > i, "unexpected character in Yul: %r" % text[i:i + 20])
        t, i = m.group(0), m.end()
        if not (t.isspace() or t.startswith("//")):
            out.append(t)
    require("".join(out) == re.sub(r"//[^\n]*|\s+", "", text), "lexer is not lossless")
    return out


def lean_tok(t):
    if t in PUNCT:
        return PUNCT[t]
    if re.fullmatch(r"0x[0-9a-fA-F]+", t):
        return "(.num 0x%x)" % int(t, 16)
    if re.fullmatch(r"[0-9]+", t):
        require(t == "0" or not t.startswith("0"), "decimal literal with a leading zero: " + t)
        return "(.num %d)" % int(t)
    require(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", t) is not None and t not in YUL_KEYWORDS,
            "unsupported Yul token: " + t)
    return '(.ident "%s")' % t


def yul_chunks(body):
    """The tokens of permute's body, in chunks of whole top-level statements (the modulus
    binding, the never-taken branch, then the 65 round blocks). Lean parses the concatenation;
    the chunks only keep the generated Lean lines short."""
    toks = lex_yul(body)
    chunks, cur, depth = [], [], 0
    for t in toks:
        cur.append(t)
        if t == "{":
            depth += 1
        elif t == "}":
            depth -= 1
            if depth == 0 and cur[0] != "let":
                chunks.append(cur)
                cur = []
        elif depth == 0 and cur[0] == "let" and len(cur) == 4:
            chunks.append(cur)
            cur = []
    require(depth == 0 and not cur, "unbalanced blocks")
    require(len(chunks) == 2 + ROUNDS, "expected 2 + 65 top-level statements, found %d" % len(chunks))
    require(chunks[0][:3] == ["let", "P", ":="] and int(chunks[0][3], 16) == P, "modulus binding")
    require(chunks[1][0] == "if", "the never-taken branch")
    return chunks


ASSEMBLY_HEAD = 'assembly ("memory-safe") {'


def assembly_body(src, label):
    """The text between the braces of the runtime's one assembly block."""
    require(src.count(ASSEMBLY_HEAD) == 1, "%s: one memory-safe assembly block" % label)
    k = src.index(ASSEMBLY_HEAD) + len(ASSEMBLY_HEAD) - 1
    depth = 0
    for e in range(k, len(src)):
        if src[e] == "{":
            depth += 1
        elif src[e] == "}":
            depth -= 1
            if depth == 0:
                return src[k + 1:e]
    require(False, "%s: unterminated assembly block" % label)


PERMUTE_HEAD_TOKS = ["function", "permute", "(", "s0", ",", "s1", ",", "s2", ")", "->", "r0", ",",
                     "r1", ",", "r2", "{"]
PERMUTE_TAIL_TOKS = ["r0", ":=", "s0", "r1", ":=", "s1", "r2", ":=", "s2", "}"]


def block_chunks(src, body, label):
    """The tokens of the whole assembly block, in named chunks: permute's header, the chunks of
    its body (`yul_chunks`), its returns, then the dispatcher's top-level pieces (the short-calldata
    check, the switch's head and each of its arms). Lean parses the concatenation (`yulBlock`)."""
    toks = lex_yul(assembly_body(src, label))
    body_chunks = yul_chunks(body)
    n_body = sum(len(c) for c in body_chunks)
    n_head = len(PERMUTE_HEAD_TOKS)
    require(toks[:n_head] == PERMUTE_HEAD_TOKS, "%s: the block starts with permute's header" % label)
    require(toks[n_head:n_head + n_body] == [t for c in body_chunks for t in c],
            "%s: permute's body tokens" % label)
    rest = toks[n_head + n_body:]
    require(rest[:len(PERMUTE_TAIL_TOKS)] == PERMUTE_TAIL_TOKS, "%s: permute's returns" % label)
    rest = rest[len(PERMUTE_TAIL_TOKS):]
    pieces, cur, depth = [], [], 0
    for t in rest:
        if depth == 0 and t in ("case", "default", "switch") and cur:
            pieces.append(cur)
            cur = []
        cur.append(t)
        if t == "{":
            depth += 1
        elif t == "}":
            depth -= 1
            if depth == 0:
                pieces.append(cur)
                cur = []
    require(depth == 0 and not cur, "%s: unbalanced dispatcher" % label)
    named = [("yulPermuteHead", PERMUTE_HEAD_TOKS)]
    named += [("yulHead%d" % i if i < 2 else "yulRound%d" % (i - 2), c) for i, c in enumerate(body_chunks)]
    named += [("yulPermuteTail", PERMUTE_TAIL_TOKS)]
    named += [("yulDispatch%d" % i, c) for i, c in enumerate(pieces)]
    require([t for _, c in named for t in c] == toks, "%s: block chunks" % label)
    return named


