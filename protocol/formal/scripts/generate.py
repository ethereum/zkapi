def permute_ref(ark, mds, s):
    s = list(s)
    for r in range(ROUNDS):
        s = [(s[i] + ark[r][i]) % P for i in range(3)]
        if r < RF_HALF or r >= RF_HALF + RP:
            s = [pow5(v) for v in s]
        else:
            s[0] = pow5(s[0])
        s = mat_vec(mds, s)
    return s


def hash_fields(ark, mds, xs):
    """arkworks PoseidonSponge: absorb all, squeeze one (rate 2, capacity 1)."""
    s = [0, 0, 0]
    xs = list(xs)
    while len(xs) > 2:
        s = permute_ref(ark, mds, [s[0], (s[1] + xs[0]) % P, (s[2] + xs[1]) % P])
        xs = xs[2:]
    if len(xs) >= 1:
        s[1] = (s[1] + xs[0]) % P
    if len(xs) == 2:
        s[2] = (s[2] + xs[1]) % P
    return permute_ref(ark, mds, s)[1]


def compress(ark, mds, c, l, r):
    return permute_ref(ark, mds, [c % P, l % P, r % P])[1]


