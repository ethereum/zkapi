def h(v):
    return "0x%064x" % v


# Indentation of the round blocks in the runtime: inside `function permute` inside the fallback's
# assembly block (contract 4, fallback 8, assembly 12, function body 16).
ROUND_INDENT = 16


class Gen:
    def __init__(self):
        self.lines = []
        self.m = {"s0": 1, "s1": 1, "s2": 1}

    def emit(self, s, ind=ROUND_INDENT):
        self.lines.append(" " * ind + s)

    def add(self, a, ma, b, mb):
        if ma + mb <= MAXM:
            return "add(%s, %s)" % (a, b), ma + mb
        return "addmod(%s, %s, P)" % (a, b), 1

    def row(self, terms, reduce_out):
        exprs = ["mulmod(%s, %s, P)" % (v, h(c)) for v, c in terms]
        e, m = exprs[0], 1
        for i, x in enumerate(exprs[1:]):
            last = i == len(exprs) - 2
            if last and reduce_out:
                e, m = "addmod(%s, %s, P)" % (e, x), 1
            else:
                e, m = self.add(e, m, x, 1)
        return e, m

    def full_round(self, k, first, last, mat):
        self.emit("{")
        for i, (v, s) in enumerate(zip("xyz", ("s0", "s1", "s2"))):
            if first:
                self.emit("    let %s := addmod(%s, %s, P)" % (v, s, h(k[i])))
            else:
                e, _ = self.add(s, self.m[s], h(k[i]), 1)
                self.emit("    let %s := %s" % (v, e))
        for v in "xyz":
            self.emit("    {")
            self.emit("        let q := mulmod(%s, %s, P)" % (v, v))
            self.emit("        %s := mulmod(mulmod(q, q, P), %s, P)" % (v, v))
            self.emit("    }")
        for i, s in enumerate(("s0", "s1", "s2")):
            e, m = self.row([("x", mat[i][0]), ("y", mat[i][1]), ("z", mat[i][2])], reduce_out=last)
            self.emit("    %s := %s" % (s, e))
            self.m[s] = m
        self.emit("}")

    def partial_scaled(self, k, b, c, w1, w2):
        e, _ = self.add("s0", self.m["s0"], h(k), 1)
        self.emit("{")
        self.emit("    let x := %s" % e)
        self.emit("    {")
        self.emit("        let q := mulmod(x, x, P)")
        self.emit("        x := mulmod(mulmod(q, q, P), x, P)")
        self.emit("    }")
        e0, m0 = self.add("x", 1, "mulmod(s1, %s, P)" % h(b), 1)
        e0, m0 = self.add(e0, m0, "mulmod(s2, %s, P)" % h(c), 1)
        self.emit("    s0 := %s" % e0)
        for s, w in (("s1", w1), ("s2", w2)):
            e, m = self.add(s, self.m[s], "mulmod(x, %s, P)" % h(w), 1)
            self.emit("    %s := %s" % (s, e))
            self.m[s] = m
        self.m["s0"] = m0
        self.emit("}")

    def last_partial(self, k, mat):
        e0, _ = self.add("s0", self.m["s0"], h(k[0]), 1)
        e1, _ = self.add("s1", self.m["s1"], h(k[1]), 1)
        e2, _ = self.add("s2", self.m["s2"], h(k[2]), 1)
        self.emit("{")
        self.emit("    let x := %s" % e0)
        self.emit("    let y := %s" % e1)
        self.emit("    let z := %s" % e2)
        self.emit("    {")
        self.emit("        let q := mulmod(x, x, P)")
        self.emit("        x := mulmod(mulmod(q, q, P), x, P)")
        self.emit("    }")
        for i, s in enumerate(("s0", "s1", "s2")):
            e, m = self.row([("x", mat[i][0]), ("y", mat[i][1]), ("z", mat[i][2])], reduce_out=False)
            self.emit("    %s := %s" % (s, e))
            self.m[s] = m
        self.emit("}")


def render_permute_body(sc, mds):
    """The body of the runtime's `function permute(s0, s1, s2) -> r0, r1, r2` up to its three
    returns, as zkapi-proof's poseidon_runtime.rs renders it: the modulus binding, the
    never-taken branch, then the 65 round blocks, one LF-terminated line each."""
    g = Gen()
    for i, k in enumerate(sc["full"][:RF_HALF]):
        g.full_round(k, first=(i == 0), last=False, mat=mds)
