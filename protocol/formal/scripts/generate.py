def check_glue(src, label):
    """Require the pinned text around the verified body: the SPDX line, then exactly
    RUNTIME_GLUE (comments and whitespace aside) with permute's body in place of BODY; no other
    function, no block comment, LF line ends."""
    require("\r" not in src and "\t" not in src, "%s: CR or tab in the source" % label)
    require(src.startswith("// SPDX-License-Identifier: MIT\n"), "%s: SPDX line" % label)
    require("/*" not in src and "*/" not in src, "%s: block comment" % label)
    names = re.findall(r"\bfunction\s+([A-Za-z_$][A-Za-z0-9_$]*)", src)
    require(names == ["permute"], "%s: the source's functions are %s" % (label, names))
    body = permute_body_of(src, label)
    glue = src.replace(body, "BODY\n", 1)
    require(normalize_sol(glue) == RUNTIME_GLUE,
            "%s: the code around permute's body differs from the pinned text" % label)
    require(normalize_sol(src).count(HASH5_ZERO) == 1, "%s: hash5's opaque zero" % label)
    return body


