def vectors_merkle_module(cv, ark, mds):
    lines = header("Known-answer vectors for `merkle_root` (zkapi-clientd poseidon-vectors.json, "
                   "computed by zkapi-core): the reference `merkleRoot` and the word-level loop "
                   "`insertPath32Word` (the unrolled program), each by kernel evaluation.",
                   [VECTORS_JSON])
    lines = ["import ZkapiFormal.Lazy.Paths", ""] + lines
    lines += ["namespace Zkapi.Vectors", "", "open Zkapi.Poseidon Zkapi.Lazy", "",
              "set_option maxRecDepth 100000", ""]
    for n, (index, leaf, sib, root) in enumerate(cv["roots"]):
        require(merkle_root_ref(ark, mds, index, leaf, sib) == root, "merkle_root vector %d" % n)
        lines += ["/-- The siblings of `rust_merkle_root_%d`, bottom up. -/" % n,
                  "def merkleRootSiblings%d : List ℕ :=" % n,
                  "  [" + ",\n   ".join(hexw(x) for x in sib) + "]", "",
                  "/-- `merkle_root(%d, leaf, siblings)`. -/" % index,
                  "theorem rust_merkle_root_%d :" % n,
                  "    merkleRoot %d (%s : F) (fun i => (merkleRootSiblings%d.getD i 0 : F)) =" % (
                      index, hexw(leaf), n),
                  "      (%s : F) := by" % hexw(root),
                  "  decide +kernel", "",
                  "/-- The same root from `insertPath32`'s loop on words. -/",
                  "theorem insertPath32_root_%d :" % n,
                  "    (insertPath32Word 0x7a6b6170692e76322e6e6f6465 %d %s (merkleRootSiblings%d.getD · 0)).1 =" % (
                      index, hexw(leaf), n),
                  "      %s := by" % hexw(root),
                  "  decide +kernel", ""]
    lines += ["end Zkapi.Vectors", ""]
    return "\n".join(lines)


def outputs(extra_yul, msp):
    ark, mds, tests = load_reference()
    if msp is not None:
        mc, mm = msp_constants(msp)
        require(mc == ark and mm == mds, "zkAPI's parameters differ from msp's circomlib t=3 params3")
    st = sparse_form(ark, mds)
    blob = deployed_blob()
    require(st["words"] == blob, "sparse form differs from Bn254Poseidon.CONSTANTS")
    sc = scaled_form(st)
    rng = random.Random(20261018)
    for _ in range(8):
        s = [rng.randrange(P) for _ in range(3)]
        r = permute_ref(ark, mds, s)
        require(permute_sparse(st, mds, s) == r and permute_scaled(sc, mds, s) == r, "forms disagree")
    require(compress(ark, mds, DOMAIN_NODE, 1, 2) == tests["test_node"], "manifest test_node")
    require(hash_fields(ark, mds, [1, 2, 3]) == tests["test_hash3"], "manifest test_hash3")
    require(hash_fields(ark, mds, [1, 2, 3, 4, 5]) == tests["test_hash5"], "manifest test_hash5")
    body = render_permute_body(sc, mds)
    runtime_src = RUNTIME_SOL.read_text()
    require(permute_body_of(runtime_src, rel(RUNTIME_SOL)) == body,
            "%s: permute's body differs from the rendered schedule" % rel(RUNTIME_SOL))
    check_glue(runtime_src, rel(RUNTIME_SOL))
    require(SETUP_RUNTIME_SOL.read_text() == runtime_src,
            "%s differs from %s" % (rel(SETUP_RUNTIME_SOL), rel(RUNTIME_SOL)))
    for path in extra_yul:
        src = Path(path).read_text()
        require(permute_body_of(src, path) == body, "%s: permute's body differs" % path)
        check_glue(src, path)
        print("%s: permute's body and the code around it match" % path)
    named = block_chunks(runtime_src, body, rel(RUNTIME_SOL))
    comp, h5 = solidity_vectors()
    zs = zero_hashes()
    cv = clientd_vectors()
    perms = permutation_vectors()
    base = FORMAL / "ZkapiFormal"
    return {
        base / "Data" / "Reference.lean": data_reference(ark, mds),
        base / "Data" / "Sparse.lean": data_sparse(st),
        base / "Data" / "Scaled.lean": data_scaled(sc),
        base / "Data" / "Yul.lean": data_yul(named),
        base / "Data" / "Deployed.lean": data_deployed(blob),
        base / "Vectors.lean": vectors_module(comp, h5, zs, cv, perms, ark, mds),
        base / "VectorsMerkle.lean": vectors_merkle_module(cv, ark, mds),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail unless the outputs regenerate exactly")
    ap.add_argument("--yul", action="append", default=[], metavar="PATH",
                    help="another copy of the runtime whose permute body must equal the rendered one "
                         "and whose code around it must be the pinned text")
    ap.add_argument("--msp", type=Path, default=None, metavar="CONSTANTS_LEAN",
                    help="msp-formal-curve Poseidon/Constants.lean, to cross-check circomlib t=3")
    args = ap.parse_args()
    outs = outputs(args.yul, args.msp)
    bad = []
    for path, text in outs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(rel(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    require(not bad, "out of date (rerun without --check): " + ", ".join(bad))
    print("ok: %d modules %s" % (len(outs), "match" if args.check else "written"))


if __name__ == "__main__":
    main()
