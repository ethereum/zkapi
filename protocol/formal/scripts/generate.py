#!/usr/bin/env python3
"""Generate the Lean data modules of protocol/formal from zkAPI's pinned Poseidon parameters.

    python3 -I protocol/formal/scripts/generate.py           # write the generated modules
    python3 -I protocol/formal/scripts/generate.py --check   # fail unless they regenerate exactly

Inputs (all inside this repository):

* protocol/setup/v2-concession-dev/manifest.json, section "poseidon": the round constants and MDS
  matrix that zkapi-proof's `poseidon_manifest()` printed from arkworks
  `find_poseidon_ark_and_mds::<Fr>(254, rate 2, 8 full, 57 partial, skip 0)`, the parameters
  zkapi-core/src/v2.rs `config()` builds at run time. This script regenerates both from the Grain
  LFSR specification (a port of arkworks' `PoseidonGrainLFSR`) and requires equality.
* protocol/contracts/test/reference/Bn254PoseidonReference.sol: the former library's 372-word
  CONSTANTS blob (the test oracle), which must equal the sparse form derived here (a port of
  compact.rs `optimized_poseidon_constants`).
* protocol/contracts/src/poseidon/Bn254PoseidonRuntime.sol: the vault's Poseidon, generated by
  zkapi-proof (poseidon_runtime.rs). Its `permute` body must equal, byte for byte, the body this
  script renders from the scaled constants it derives (a port of params.py `scaled_constants`
  and gen_unrolled.py `permutation_body`), and everything around it (the contract, its fallback,
  the dispatcher and ABI checks of the four entry points, hash5's opaque zero) must be the pinned
  text below (`check_glue`). The setup's copy (protocol/setup/v2-concession-dev) must be the same
  file. Additional copies are checked the same way with --yul PATH.
* protocol/contracts/test/Bn254PoseidonRuntime.t.sol, protocol/contracts/src/libraries/MerkleUpdateLib.sol,
  zkapi-clientd/internal/zkapi/testdata/poseidon-vectors.json and
  protocol/formal/reference/permutation-vectors.json (arkworks, all three lanes, see
  scripts/arkworks-vectors): test vectors for the kernel-checked sanity theorems.

Generation is not a proof. Every algebraic fact the Lean proofs use about the generated data
(changes of basis, constant relocation, scaling factors) is re-checked by the Lean kernel. The Yul
is handed to Lean as the token stream of the runtime's whole assembly block (`lex_yul`, which drops
only whitespace and comments); Lean parses it with its own Yul grammar (ZkapiFormal/Yul/Syntax.lean),
checks the parse against the verified program and its own statement of the dispatcher
(ZkapiFormal/Yul/Permute.lean, Shape.lean) and proves every entry point for all calldata
(ZkapiFormal/Yul/Entry.lean). The pinned text (`check_glue`) is a second, independent guard on the
code the proofs cover, and the only one on the Solidity around the block. What this script is
trusted for is listed in protocol/formal/README.md.

Parts of this file are ports, with attribution, of:
* arkworks ark-crypto-primitives `sponge/poseidon/grain_lfsr.rs` (MIT/Apache-2.0);
* zkapi-proof `compact.rs` `optimized_poseidon_constants` and the Poseidon prototype's
  `gen/params.py` `optimized_constants` / `scaled_constants` (poseidon-proto, not kept in this
  repository; zkapi-proof `poseidon_runtime.rs` `scaled_schedule` is its production port);
* the prototype's `gen/gen_unrolled.py` `Gen` / `permutation_body` (production port:
  `poseidon_runtime.rs` `permute_body`, which renders the runtime this script checks);
* msp-formal-curve `Poseidon/small_optimized_generate.py` (Apache-2.0, same author): the
  certificate approach (basis and translation witnesses, Lean-checked by `decide`).
"""

