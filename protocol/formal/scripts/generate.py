class Grain:
    """arkworks PoseidonGrainLFSR (Poseidon paper, appendix F): field type 1 (prime field),
    S-box 0 (x^alpha), then n, t, R_F, R_P, thirty ones; 160 discarded updates."""

    def __init__(self, n, t, rf, rp):
        st = [False] * 80
        st[1] = True  # b0 b1 = 01: prime field
        # b2..b5 = 0000: x^alpha S-box

        def put(lo, hi, v):
            for i in range(hi, lo - 1, -1):
                st[i] = bool(v & 1)
                v >>= 1

        put(6, 17, n)
        put(18, 29, t)
        put(30, 39, rf)
        put(40, 49, rp)
        for i in range(50, 80):
            st[i] = True
        self.st, self.head = st, 0
        for _ in range(160):
            self.update()

    def update(self):
        s, h = self.st, self.head
        b = s[(h + 62) % 80] ^ s[(h + 51) % 80] ^ s[(h + 38) % 80] ^ s[(h + 23) % 80] \
            ^ s[(h + 13) % 80] ^ s[h]
        s[h] = b
        self.head = (h + 1) % 80
        return b

    def bits(self, k):
        out = []
        for _ in range(k):
            b = self.update()
            while not b:
                self.update()
                b = self.update()
            out.append(self.update())
        return out

    def number(self, k):
        v = 0
        for b in self.bits(k):
            v = 2 * v + int(b)
        return v

    def rejection(self, count, n=254):
        out = []
        for _ in range(count):
            while True:
                v = self.number(n)
                if v < P:
                    out.append(v)
                    break
        return out

    def mod_p(self, count, n=254):
        return [self.number(n) % P for _ in range(count)]


def grain_parameters():
    """arkworks find_poseidon_ark_and_mds::<Fr>(254, rate 2, 8, 57, skip_matrices 0)."""
    g = Grain(254, T, 2 * RF_HALF, RP)
    ark = [g.rejection(T) for _ in range(ROUNDS)]
    xs, ys = g.mod_p(T), g.mod_p(T)
    mds = [[inv((xs[i] + ys[j]) % P) for j in range(T)] for i in range(T)]
    return ark, mds


def load_reference():
    m = json.loads(MANIFEST.read_text())["poseidon"]
    require(int(m["field_modulus"], 16) == P, "manifest field modulus")
    require((m["full_rounds"], m["partial_rounds"], m["alpha"], m["rate"], m["capacity"])
            == (8, 57, 5, 2, 1), "manifest round schedule")
    flat = [int(x, 16) for x in m["round_constants"]]
    require(len(flat) == 3 * ROUNDS, "manifest round-constant count")
    ark = [flat[3 * r:3 * r + 3] for r in range(ROUNDS)]
    md = [int(x, 16) for x in m["mds"]]
    require(len(md) == 9, "manifest MDS size")
    mds = [md[3 * i:3 * i + 3] for i in range(3)]
    require(all(0 <= v < P for row in ark + mds for v in row), "non-canonical constant")
    g_ark, g_mds = grain_parameters()
    require(g_ark == ark, "manifest round constants differ from the Grain LFSR regeneration")
    require(g_mds == mds, "manifest MDS differs from the Grain LFSR regeneration")
    tests = {k: int(m[k], 16) for k in ("test_hash3", "test_hash5", "test_node")}
    return ark, mds, tests


def msp_constants(path):
    """params3 of msp-formal-curve/Poseidon/Constants.lean (circomlib t=3), optional."""
    src = path.read_text()
    body = src.split("def params3", 1)[1].split("def params4", 1)[0]
    cons = body.split("constants :=", 1)[1].split("matrix :=", 1)[0]
    mat = body.split("matrix :=", 1)[1]
    num = lambda s: [int(x) for x in re.findall(r"\b\d{2,}\b", s)]
    c, mm = num(cons), num(mat)
    return [c[3 * r:3 * r + 3] for r in range(ROUNDS)], [mm[3 * i:3 * i + 3] for i in range(3)]


