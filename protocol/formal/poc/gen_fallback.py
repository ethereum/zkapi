#!/usr/bin/env python3
"""Proof-of-concept source for the implementation layer (not deployed anywhere).

    python3 -I protocol/formal/poc/gen_fallback.py           # write the source and its Lean tokens
    python3 -I protocol/formal/poc/gen_fallback.py --check   # fail unless both regenerate exactly

Writes PoseidonFallback.sol and ZkapiPoC/Data.lean (the token stream of its assembly block, for
the kernel to parse). PoseidonFallback.sol is a contract whose runtime is, apart from solc's
`mstore(0x40, 0x80)`
prologue, one inline-assembly block holding the dispatcher, the ABI check and the permutation as a
Yul function. The permutation body is the production runtime's `permute` body, verbatim
(protocol/contracts/src/poseidon/Bn254PoseidonRuntime.sol, the same shape with four entry
points). Only `compress(uint256,uint256,uint256)` is dispatched: the point is to prove an entry
point end to end, for all calldata, against Yul semantics (ZkapiPoC/Compress.lean).
"""
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNTIME = HERE.parent.parent / "contracts" / "src" / "poseidon" / "Bn254PoseidonRuntime.sol"
OUT = HERE / "PoseidonFallback.sol"
DATA = HERE / "ZkapiPoC" / "Data.lean"

LEX = re.compile(r"\s+|//[^\n]*|->|0x[0-9a-fA-F]+|[0-9]+|[A-Za-z_][A-Za-z0-9_]*|:=|[{}(),]")
KEYWORDS = {"let": ".kwLet", "if": ".kwIf", "function": ".kwFunction", "switch": ".kwSwitch",
            "case": ".kwCase", "default": ".kwDefault", "{": ".lb", "}": ".rb", "(": ".lp",
            ")": ".rp", ",": ".comma", ":=": ".assign", "->": ".arrow"}
UNSUPPORTED = {"for", "leave", "break", "continue", "true", "false", "hex"}


def lex(text):
    """Tokens of Yul source: every character is consumed by one alternative of LEX; only
    whitespace and `//` comments are dropped."""
    out, i = [], 0
    while i < len(text):
        m = LEX.match(text, i)
        if m is None or m.end() == i:
            raise SystemExit("unexpected character in Yul: %r" % text[i:i + 20])
        t, i = m.group(0), m.end()
        if not (t.isspace() or t.startswith("//")):
            out.append(t)
    if "".join(out) != re.sub(r"//[^\n]*|\s+", "", text):
        raise SystemExit("lexer is not lossless")
    return out


def lean_tok(t):
    if t in KEYWORDS:
        return KEYWORDS[t]
    if re.fullmatch(r"0x[0-9a-fA-F]+", t):
        return "(.num 0x%x)" % int(t, 16)
    if re.fullmatch(r"[0-9]+", t):
        return "(.num %d)" % int(t)
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", t) or t in UNSUPPORTED:
        raise SystemExit("unsupported Yul token: " + t)
    return '(.ident "%s")' % t


def assembly_body(src):
    head = 'assembly ("memory-safe") {'
    i = src.index(head)
    k = i + len(head) - 1
    depth = 0
    for e in range(k, len(src)):
        if src[e] == "{":
            depth += 1
        elif src[e] == "}":
            depth -= 1
            if depth == 0:
                return src[k + 1:e]
    raise SystemExit("unterminated assembly block")


def render_data(sol):
    toks = [lean_tok(t) for t in lex(assembly_body(sol))]
    chunks = [toks[i:i + 600] for i in range(0, len(toks), 600)]
    lines = ["import ZkapiPoC.Syntax",
             "/- Generated by protocol/formal/poc/gen_fallback.py; do not edit by hand.",
             "",
             "   Token stream of the assembly block of protocol/formal/poc/PoseidonFallback.sol",
             "   (SHA-256 %s), in chunks of 600 tokens." % hashlib.sha256(sol.encode()).hexdigest(),
             "-/", "", "namespace Zkapi.PoC.Data", "", "open Zkapi.PoC (Tok)", ""]
    for i, c in enumerate(chunks):
        lines += ["def chunk%d : List Tok :=" % i, "  [" + ", ".join(c) + "]", ""]
    lines += ["/-- The fallback's assembly block body, in source order. -/",
              "def fallbackBody : List Tok :=",
              "  " + " ++\n  ".join("chunk%d" % i for i in range(len(chunks))), "",
              "end Zkapi.PoC.Data", ""]
    return "\n".join(lines)


def permute_body(src):
    """The production runtime's `permute` body, up to its three returns."""
    head = "            function permute(s0, s1, s2) -> r0, r1, r2 {\n"
    tail = "                r0 := s0\n"
    if src.count(head) != 1:
        raise SystemExit("no unique permute function in the runtime")
    start = src.index(head) + len(head)
    end = src.index(tail, start)
    return src[start:end]


def render():
    body = permute_body(RUNTIME.read_text()).rstrip("\n")
    return """// SPDX-License-Identifier: MIT
pragma solidity ^0.8.28;

/// @notice Proof of concept (protocol/formal/poc): compress(uint256,uint256,uint256) with the
///         dispatcher, the ABI check and the unrolled permutation in one inline-assembly block.
///         Generated by gen_fallback.py from protocol/contracts/src/poseidon/Bn254PoseidonRuntime.sol.
contract PoseidonFallback {
    fallback() external payable {
        assembly ("memory-safe") {
            function permute(s0, s1, s2) -> r0, r1, r2 {
%s
                r0 := s0
                r1 := s1
                r2 := s2
            }
            if lt(calldatasize(), 4) { revert(0, 0) }
            switch shr(224, calldataload(0))
            case 0x2d0c7694 {
                if slt(sub(calldatasize(), 4), 96) { revert(0, 0) }
                let out0, out1, out2 := permute(calldataload(4), calldataload(36), calldataload(68))
                mstore(0, out1)
                return(0, 32)
            }
            default { revert(0, 0) }
        }
    }
}
""" % body


def main():
    text = render()
    outs = {OUT: text, DATA: render_data(text)}
    if "--check" in sys.argv:
        for path, value in outs.items():
            if not path.exists() or path.read_text() != value:
                raise SystemExit("gen_fallback.py: %s is out of date" % path.name)
        print("ok: PoseidonFallback.sol and ZkapiPoC/Data.lean match")
    else:
        for path, value in outs.items():
            path.write_text(value)
        print("ok: PoseidonFallback.sol and ZkapiPoC/Data.lean written")


if __name__ == "__main__":
    main()
