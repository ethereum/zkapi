/// Which statement a key file belongs to (the last label of its header).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum KeyKind {
    Request,
    Withdrawal,
}

impl KeyKind {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Request => "request",
            Self::Withdrawal => "withdrawal",
        }
    }

    /// Public inputs of the statement (instance variables minus "one").
    pub const fn public_inputs(self) -> usize {
        match self {
            Self::Request => REQUEST_PUBLIC_INPUTS,
            Self::Withdrawal => WITHDRAWAL_PUBLIC_INPUTS,
        }
    }

    pub const fn proving_key_file(self) -> &'static str {
        match self {
            Self::Request => REQUEST_PROVING_KEY_FILE,
            Self::Withdrawal => WITHDRAWAL_PROVING_KEY_FILE,
        }
    }

    pub const fn verifying_key_file(self) -> &'static str {
        match self {
            Self::Request => REQUEST_VERIFYING_KEY_FILE,
            Self::Withdrawal => WITHDRAWAL_VERIFYING_KEY_FILE,
        }
    }
}

impl std::fmt::Display for KeyKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Setup IDs this build accepts: [`RELEASE_SETUP_IDS`], plus [`DEV_SETUP_ID`]
/// and [`REHEARSAL_SETUP_ID`] with the `dev-setup` feature. A release build
/// additionally requires an `mpc-1` key to be pinned ([`check_setup_accepted`]).
pub fn accepted_setup_ids() -> &'static [&'static str] {
    accepted_setup_ids_for(dev_setup_build())
}

/// Whether this build has the `dev-setup` feature (accepts development keys).
pub const fn dev_setup_build() -> bool {
    cfg!(feature = "dev-setup")
}

/// The setup ids accepted by a build with (`true`) or without the
/// `dev-setup` feature.
pub const fn accepted_setup_ids_for(dev_setup: bool) -> &'static [&'static str] {
    if dev_setup {
        DEV_BUILD_SETUP_IDS
    } else {
        RELEASE_SETUP_IDS
    }
}

/// The setup policy of this build for a key of `setup_id` and `kind` whose
/// verifying key hashes to `vk_keccak256`:
/// * without `dev-setup` (release): only `mpc-1`, and only the pinned keys of
///   [`CEREMONY_VK_KECCAK256`];
/// * with `dev-setup`: also `dev`, `rehearsal` and unpinned `mpc-1` keys (the
///   G-SETUP proving gate runs on the imported keys before they are pinned).
pub fn check_setup_accepted(setup_id: &str, kind: KeyKind, vk_keccak256: &[u8; 32]) -> Result<()> {
    check_setup_accepted_for(
        setup_id,
        kind,
        vk_keccak256,
        dev_setup_build(),
        CEREMONY_VK_KECCAK256.as_ref(),
    )
}

/// [`check_setup_accepted`] for an explicit build (`dev_setup`) and pin set.
pub fn check_setup_accepted_for(
    setup_id: &str,
    kind: KeyKind,
    vk_keccak256: &[u8; 32],
    dev_setup: bool,
    ceremony_pins: Option<&VkPins>,
) -> Result<()> {
    let accepted = accepted_setup_ids_for(dev_setup);
    ensure!(
        accepted.contains(&setup_id),
        "setup {setup_id:?} is not accepted by this build (accepted: {accepted:?}); \
         development and rehearsal keys load only with the dev-setup feature"
    );
    if setup_id == CEREMONY_SETUP_ID && !dev_setup {
        let pins = ceremony_pins.ok_or_else(|| {
            anyhow!(
                "no {CEREMONY_SETUP_ID} verifying keys are pinned in this build \
                 (CEREMONY_VK_KECCAK256): a key labelled {CEREMONY_SETUP_ID} is not trusted by its label"
            )
        })?;
        ensure!(
            pins.get(kind) == vk_keccak256,
            "the {kind} key is labelled {CEREMONY_SETUP_ID} but its verifying key {} is not \
             the pinned ceremony key {}",
            hex32(vk_keccak256),
            hex32(pins.get(kind))
        );
    }
    Ok(())
}

fn check_setup_id_syntax(setup_id: &str) -> Result<()> {
    ensure!(
        !setup_id.is_empty()
            && setup_id.len() <= 32
            && setup_id
                .bytes()
                .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-'),
        "setup id must be 1-32 characters of [a-z0-9-]"
    );
    Ok(())
}

/// `zkapi-v2-concession-v1/<setup_id>/<kind>\0`, the header of every key file.
pub fn key_header(setup_id: &str, kind: KeyKind) -> Result<Vec<u8>> {
    check_setup_id_syntax(setup_id)?;
    Ok(format!("{CIRCUIT_ID}/{setup_id}/{kind}\0").into_bytes())
}

/// Split a key file into its setup id and the arkworks bytes after the header.
/// Rejects another circuit (including the legacy single-label
/// `zkapi-v2-note-bound-v1\0` header) and a key of the other kind. It does
/// not apply the build's setup policy; see [`decode_compressed`].
pub fn strip_key_header(bytes: &[u8], kind: KeyKind) -> Result<(String, &[u8])> {
    let prefix = format!("{CIRCUIT_ID}/");
    let rest = bytes.strip_prefix(prefix.as_bytes()).ok_or_else(|| {
        anyhow!(
            "incompatible setup: expected a {CIRCUIT_ID} key; keys of other circuits, \
             including zkapi-v2-note-bound-v1, must not be used"
        )
    })?;
    let end = rest
        .iter()
        .take(64)
        .position(|byte| *byte == 0)
        .ok_or_else(|| anyhow!("malformed {CIRCUIT_ID} key header"))?;
    let label = std::str::from_utf8(&rest[..end]).context("malformed key header")?;
    let (setup_id, file_kind) = label
        .split_once('/')
        .ok_or_else(|| anyhow!("malformed {CIRCUIT_ID} key header"))?;
    check_setup_id_syntax(setup_id)?;
    ensure!(
        file_kind == kind.as_str(),
        "wrong key kind: the file holds a {file_kind} key, expected a {kind} key"
    );
    Ok((setup_id.to_string(), &rest[end + 1..]))
}

/// A key stored in a setup file: a proving key or a verifying key.
pub trait SetupKey: CanonicalSerialize + CanonicalDeserialize {
    fn verifying_key(&self) -> &VerifyingKey<Bn254>;
}

impl SetupKey for ProvingKey<Bn254> {
    fn verifying_key(&self) -> &VerifyingKey<Bn254> {
        &self.vk
    }
}

impl SetupKey for VerifyingKey<Bn254> {
    fn verifying_key(&self) -> &VerifyingKey<Bn254> {
        self
    }
}

/// Decode a key file under this build's setup policy
/// ([`check_setup_accepted`]). Returns the key and its setup id.
pub fn decode_compressed<T: SetupKey>(bytes: &[u8], kind: KeyKind) -> Result<(T, String)> {
    decode_compressed_for(
        bytes,
        kind,
        dev_setup_build(),
        CEREMONY_VK_KECCAK256.as_ref(),
    )
}

/// Decode a key file under the policy of a build with (`dev_setup = true`)
/// or without the `dev-setup` feature and the given ceremony pins. Tests use
/// it to exercise the release policy from a development build.
pub fn decode_compressed_for<T: SetupKey>(
    bytes: &[u8],
    kind: KeyKind,
    dev_setup: bool,
    ceremony_pins: Option<&VkPins>,
) -> Result<(T, String)> {
    let (setup_id, mut payload) = strip_key_header(bytes, kind)?;
    let accepted = accepted_setup_ids_for(dev_setup);
    // Refuse a foreign setup before spending time on decoding it.
    ensure!(
        accepted.contains(&setup_id.as_str()),
        "setup {setup_id:?} is not accepted by this build (accepted: {accepted:?}); \
         development and rehearsal keys load only with the dev-setup feature"
    );
    let value = T::deserialize_compressed(&mut payload)
        .map_err(|error| anyhow!("deserialize {kind} key: {error}"))?;
    ensure!(payload.is_empty(), "trailing setup key bytes");
    check_setup_accepted_for(
        &setup_id,
        kind,
        &vk_hash(value.verifying_key()),
        dev_setup,
        ceremony_pins,
    )?;
    Ok((value, setup_id))
}

/// Header plus arkworks compressed bytes.
pub fn encode_compressed<T: CanonicalSerialize>(
    value: &T,
    setup_id: &str,
    kind: KeyKind,
) -> Result<Vec<u8>> {
    let mut bytes = key_header(setup_id, kind)?;
    value
        .serialize_compressed(&mut bytes)
        .with_context(|| format!("encode {kind} key"))?;
    Ok(bytes)
}

/// keccak256 of a verifying key's arkworks compressed bytes (the `.vk` file
/// without its header): the adapter's `REQUEST_VK_HASH` / `WITHDRAWAL_VK_HASH`.
pub fn verifying_key_keccak256(vk_file: &[u8], kind: KeyKind) -> Result<[u8; 32]> {
    let (_, payload) = strip_key_header(vk_file, kind)?;
    Ok(keccak256(payload))
}

fn vk_hash(key: &VerifyingKey<Bn254>) -> [u8; 32] {
    let mut bytes = Vec::new();
    key.serialize_compressed(&mut bytes)
        .expect("in-memory serialization");
    keccak256(&bytes)
}

pub fn keccak256(bytes: &[u8]) -> [u8; 32] {
    Keccak256::digest(bytes).into()
}

pub fn sha256(bytes: &[u8]) -> [u8; 32] {
    Sha256::digest(bytes).into()
}

fn ensure_key_shape(key: &VerifyingKey<Bn254>, kind: KeyKind) -> Result<()> {
    ensure!(
        key.gamma_abc_g1.len() == kind.public_inputs() + 1,
        "{kind} verifying key has {} IC points, expected {}",
        key.gamma_abc_g1.len(),
        kind.public_inputs() + 1
    );
    Ok(())
}

fn read_key_file(directory: &Path, file: &str) -> Result<Vec<u8>> {
    let path = directory.join(file);
    fs::read(&path).with_context(|| format!("read {}", path.display()))
}

fn verify_raw(
    key: &VerifyingKey<Bn254>,
    kind: KeyKind,
    public_inputs: &[Felt252],
    proof: &Groth16ProofWire,
) -> Result<bool> {
    ensure!(
        public_inputs.len() == kind.public_inputs(),
        "{kind} statement has {} public inputs, expected {}",
        public_inputs.len(),
        kind.public_inputs()
    );
    ensure_backend(proof)?;
    let proof = proof_from_wire(proof)?;
    // Like the adapter, which returns false for any word >= SCALAR_MODULUS:
    // reducing mod r would let N and N + r name the same statement.
    if !public_inputs.iter().all(is_canonical) {
        return Ok(false);
    }
    let inputs = public_inputs.iter().map(field).collect::<Vec<_>>();
    crate::groth16::verify_field_elements(key, &inputs, &proof)
        .map_err(|error| anyhow!("{kind} verification failed: {error}"))
}

/// Private request witness.
///
/// Genesis is `current_anchor == 1` (`B == D`, no signature). A signed state
/// needs `prev_anchor`, the anchor of the state whose request produced it:
/// the circuit checks `current_anchor == next_anchor(nullifier(s, n, prev_anchor))`.
/// `None` is accepted only at genesis (the prover then passes 0).
#[derive(Clone, Debug)]
pub struct RequestWitnessData {
    pub secret: Felt252,
    pub request_context: Felt252,
    pub note_id: u32,
    pub deposit_amount: u128,
    pub expiry: u64,
    pub merkle_siblings: [Felt252; MERKLE_DEPTH],
    pub current_balance: u128,
    pub current_blinding: Felt252,
    pub rerandomization: Felt252,
    pub current_anchor: Felt252,
    pub prev_anchor: Option<Felt252>,
    pub state_signature: Option<SchnorrSignature>,
}

impl RequestWitnessData {
    pub fn is_genesis(&self) -> bool {
        self.current_anchor == core::GENESIS_ANCHOR
    }
}

/// Private withdrawal witness plus the exit parameters the owner chooses.
///
/// `state_balance` is the balance `B` of the opened state; the statement pays
/// `final_balance = B - conceded`. `kind`, `conceded` and `valid_until` must
/// equal the statement's. Kind 1 needs `clearance_signature`.
#[derive(Clone, Debug)]
pub struct WithdrawalWitnessData {
    pub secret: Felt252,
    pub deposit_amount: u128,
    pub expiry: u64,
    pub merkle_siblings: [Felt252; MERKLE_DEPTH],
    pub state_balance: u128,
    pub state_blinding: Felt252,
    pub current_anchor: Felt252,
    pub kind: WithdrawalKind,
    pub conceded: u128,
    pub valid_until: u64,
    pub state_signature: Option<SchnorrSignature>,
    pub clearance_signature: Option<SchnorrSignature>,
}

/// The deployment and destination fields of a withdrawal statement that the
/// witness does not determine.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WithdrawalStatementParams {
    pub protocol_version: u16,
    pub chain_id: u64,
    pub contract_address: Felt252,
    pub active_root: Felt252,
    pub state_signing_key: CurvePointWire,
    pub clearance_signing_key: CurvePointWire,
    pub note_id: u32,
    /// Must be all zero for an ownership proof (kind 2).
    pub destination: [u8; 20],
}

/// Build the withdrawal statement for `witness` with the canonical
/// prover-side values: `withdrawal_nullifier = N(τ)`,
/// `next_nullifier = N(succ(N(τ)))` for an escape and 0 otherwise,
/// `final_balance = state_balance - conceded`.
pub fn withdrawal_public_inputs(
    params: &WithdrawalStatementParams,
    witness: &WithdrawalWitnessData,
) -> Result<WithdrawalPublicInputsV2C> {
    let final_balance = witness
        .state_balance
        .checked_sub(witness.conceded)
        .ok_or_else(|| anyhow!("conceded amount exceeds the state balance"))?;
    let withdrawal_nullifier =
        core::nullifier(&witness.secret, params.note_id, &witness.current_anchor);
    let next_nullifier = match witness.kind {
        WithdrawalKind::Escape => {
            core::successor_nullifier(&witness.secret, params.note_id, &witness.current_anchor)
        }
        WithdrawalKind::MutualClose | WithdrawalKind::Ownership => Felt252::ZERO,
    };
    let public = WithdrawalPublicInputsV2C {
        protocol_version: params.protocol_version,
        chain_id: params.chain_id,
        contract_address: params.contract_address,
        active_root: params.active_root,
        state_signing_key_x: params.state_signing_key.x,
        state_signing_key_y: params.state_signing_key.y,
        clearance_signing_key_x: params.clearance_signing_key.x,
        clearance_signing_key_y: params.clearance_signing_key.y,
        note_id: params.note_id,
        final_balance,
        destination: params.destination,
        withdrawal_nullifier,
        kind: witness.kind.as_u8(),
        next_nullifier,
        conceded: witness.conceded,
        valid_until: witness.valid_until,
    };
    check_withdrawal_rules(&public, witness)?;
    Ok(public)
}

pub struct RequestProver {
    key: ProvingKey<Bn254>,
    setup_id: String,
}

impl RequestProver {
    /// Decode the proving-key file bytes supplied by the caller.
    /// Browser clients use this because WebAssembly has no native filesystem.
    pub fn from_bytes(bytes: &[u8]) -> Result<Self> {
        let (key, setup_id): (ProvingKey<Bn254>, _) =
            decode_compressed(bytes, KeyKind::Request).context("decode request proving key")?;
        ensure_key_shape(&key.vk, KeyKind::Request)?;
        Ok(Self { key, setup_id })
    }

    pub fn load(directory: impl AsRef<Path>) -> Result<Self> {
        Self::from_bytes(&read_key_file(
            directory.as_ref(),
            REQUEST_PROVING_KEY_FILE,
        )?)
    }

    pub fn setup_id(&self) -> &str {
        &self.setup_id
    }

    /// keccak256 of the embedded verifying key (equals `REQUEST_VK_HASH`).
    pub fn verifying_key_keccak256(&self) -> [u8; 32] {
        vk_hash(&self.key.vk)
    }

    pub fn prove(
        &self,
        public: &RequestPublicInputsV2,
        witness: RequestWitnessData,
    ) -> Result<Groth16ProofWire> {
        check_request_rules(public, &witness)?;
        let circuit = request_circuit(public, &witness)?;
        validate_witness(circuit.clone())?;
        let proof = prove_request(&self.key, circuit, &mut OsRng)
            .map_err(|error| anyhow!("request proving failed: {error}"))?;
        proof_to_wire(&proof)
    }
}

