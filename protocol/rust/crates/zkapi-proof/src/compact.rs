/// Generate the single-party development setup (setup id [`DEV_SETUP_ID`])
/// with `Groth16::<Bn254, CircomReduction>::circuit_specific_setup` and OS
/// randomness, and write it with [`write_setup_directory`]. Available in
/// every build; only builds with the `dev-setup` feature load these keys.
pub fn setup(directory: impl AsRef<Path>) -> Result<()> {
    use crate::groth16::{request_setup, withdrawal_setup};
    let (request_pk, _) = request_setup(request_template(), &mut OsRng)
        .map_err(|error| anyhow!("request setup failed: {error}"))?;
    let (withdrawal_pk, _) = withdrawal_setup(withdrawal_template(), &mut OsRng)
        .map_err(|error| anyhow!("withdrawal setup failed: {error}"))?;
    write_setup_directory(
        directory,
        DEV_SETUP_ID,
        &request_pk,
        &withdrawal_pk,
        &SetupProvenance::default(),
    )
    .map(|_| ())
}

/// Write a setup directory: the four key files with
/// `zkapi-v2-concession-v1/<setup_id>/<kind>` headers, `manifest.json`,
/// `Bn254Poseidon.sol` and `Groth16ProofAdapter.sol` (with
/// `CIRCUIT_ID_HASH`, `REQUEST_VK_HASH` and `WITHDRAWAL_VK_HASH`). Used by
/// [`setup`] and by `examples/import_zkey.rs` for the ceremony keys.
pub fn write_setup_directory(
    directory: impl AsRef<Path>,
    setup_id: &str,
    request_pk: &ProvingKey<Bn254>,
    withdrawal_pk: &ProvingKey<Bn254>,
    provenance: &SetupProvenance,
) -> Result<SetupManifest> {
    check_setup_id_syntax(setup_id)?;
    ensure_key_shape(&request_pk.vk, KeyKind::Request)?;
    ensure_key_shape(&withdrawal_pk.vk, KeyKind::Withdrawal)?;
    let directory = directory.as_ref();
    fs::create_dir_all(directory)
        .with_context(|| format!("create setup directory {}", directory.display()))?;

    let mut files = BTreeMap::new();
    for (file, bytes) in [
        (
            REQUEST_PROVING_KEY_FILE,
            encode_compressed(request_pk, setup_id, KeyKind::Request)?,
        ),
        (
            REQUEST_VERIFYING_KEY_FILE,
            encode_compressed(&request_pk.vk, setup_id, KeyKind::Request)?,
        ),
        (
            WITHDRAWAL_PROVING_KEY_FILE,
            encode_compressed(withdrawal_pk, setup_id, KeyKind::Withdrawal)?,
        ),
        (
            WITHDRAWAL_VERIFYING_KEY_FILE,
            encode_compressed(&withdrawal_pk.vk, setup_id, KeyKind::Withdrawal)?,
        ),
    ] {
        let path = directory.join(file);
        fs::write(&path, &bytes).with_context(|| format!("write {}", path.display()))?;
        files.insert(file.to_string(), hex::encode(sha256(&bytes)));
    }
    let request_vk_hash = vk_hash(&request_pk.vk);
    let withdrawal_vk_hash = vk_hash(&withdrawal_pk.vk);
    let manifest = SetupManifest {
        circuit_id: CIRCUIT_ID.to_string(),
        setup_id: setup_id.to_string(),
        protocol_version: zkapi_types::PROTOCOL_VERSION,
        proof_backend: "groth16_bn254".to_string(),
        reduction: REDUCTION.to_string(),
        files,
        vk_keccak256: KindHashes {
            request: hex32(&request_vk_hash),
            withdrawal: hex32(&withdrawal_vk_hash),
        },
        r1cs_sha256: KindHashes {
            request: hex::encode(sha256(&crate::r1cs::r1cs_bytes(KeyKind::Request)?)),
            withdrawal: hex::encode(sha256(&crate::r1cs::r1cs_bytes(KeyKind::Withdrawal)?)),
        },
        ptau_sha256: provenance.ptau_sha256.clone(),
        transcript_sha256: provenance.transcript_sha256.clone(),
        zkey_sha256: provenance.zkey_sha256.clone(),
        circuits: CircuitShapes {
            request: circuit_shape(KeyKind::Request)?,
            withdrawal: circuit_shape(KeyKind::Withdrawal)?,
        },
        request: verifying_key_manifest(&request_pk.vk),
        withdrawal: verifying_key_manifest(&withdrawal_pk.vk),
        poseidon: poseidon_manifest(),
    };
    let mut manifest_json = serde_json::to_vec_pretty(&manifest).context("encode manifest")?;
    manifest_json.push(b'\n');
    fs::write(directory.join(SETUP_MANIFEST_FILE), manifest_json)
        .context("write setup manifest")?;
    fs::write(
        directory.join(SOLIDITY_POSEIDON_FILE),
        poseidon_solidity_source(),
    )
    .context("write Solidity Poseidon library")?;
    fs::write(
        directory.join(SOLIDITY_VERIFIER_FILE),
        groth16_solidity_source(setup_id, &request_pk.vk, &withdrawal_pk.vk),
    )
    .context("write Solidity Groth16 adapter")?;
    Ok(manifest)
}

