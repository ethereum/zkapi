//! Stable native interface for zkAPI Groth16 proofs and curve operations,
//! circuit `zkapi-v2-concession-v1`.
//!
//! * Statements: [`RequestPublicInputsV2`] (12 inputs, unchanged) and
//!   [`WithdrawalPublicInputsV2C`] (16 inputs); witnesses:
//!   [`RequestWitnessData`] and [`WithdrawalWitnessData`].
//! * Provers and verifiers: [`RequestProver`], [`RequestVerifier`],
//!   [`WithdrawalProver`], [`WithdrawalVerifier`]. Every prover is
//!   [`Prover`] (`Groth16<Bn254, CircomReduction>`); verification is standard
//!   Groth16 and independent of the reduction.
//! * Key files: `zkapi-v2-concession-v1/<setup_id>/<kind>\0` followed by the
//!   arkworks compressed key ([`key_header`], [`decode_compressed`]). Release
//!   builds accept only [`RELEASE_SETUP_IDS`], and an `mpc-1` key only when its
//!   verifying key is pinned in [`CEREMONY_VK_KECCAK256`]; the `dev-setup`
//!   feature also accepts [`DEV_SETUP_ID`], [`REHEARSAL_SETUP_ID`] and unpinned
//!   `mpc-1` keys ([`check_setup_accepted`]).
//! * Setup directories: [`write_setup_directory`] writes the four keys,
//!   `manifest.json` ([`SetupManifest`]) and the generated Solidity
//!   (`Bn254Poseidon.sol`, `Groth16ProofAdapter.sol`); [`setup`] generates the
//!   development setup. Generating keys needs no feature: only accepting
//!   development keys does.

