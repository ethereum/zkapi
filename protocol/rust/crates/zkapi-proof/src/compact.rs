/// Constraint counts of one circuit.
#[derive(Clone, Copy, Debug, Serialize, Deserialize, PartialEq, Eq)]
pub struct CircuitShape {
    pub constraints: usize,
    pub public_inputs: usize,
    pub witness_variables: usize,
    /// QAP domain size: the next power of two of constraints + instance variables.
    pub domain_size: usize,
}

/// Synthesize a circuit's template and report its shape.
pub fn circuit_shape(kind: KeyKind) -> Result<CircuitShape> {
    let cs = match kind {
        KeyKind::Request => synthesize(request_template(), SynthesisMode::Setup),
        KeyKind::Withdrawal => synthesize(withdrawal_template(), SynthesisMode::Setup),
    }
    .map_err(|error| anyhow!("synthesize {kind} template: {error}"))?;
    let rows = cs.num_constraints() + cs.num_instance_variables();
    Ok(CircuitShape {
        constraints: cs.num_constraints(),
        public_inputs: cs.num_instance_variables() - 1,
        witness_variables: cs.num_witness_variables(),
        domain_size: rows.next_power_of_two(),
    })
}

