struct Keys {
    request_prover: RequestProver,
    request_verifier: RequestVerifier,
    withdrawal_prover: WithdrawalProver,
    withdrawal_verifier: WithdrawalVerifier,
    /// One prover and verifier per batch size of [`INSERTION_SIZES`].
    insertion: Vec<(InsertionProver, InsertionVerifier)>,
}

impl Keys {
    fn insertion(&self, size: usize) -> &(InsertionProver, InsertionVerifier) {
        let index = INSERTION_SIZES.iter().position(|k| *k == size).unwrap();
        &self.insertion[index]
    }
}

fn keys() -> &'static Keys {
    static KEYS: OnceLock<Keys> = OnceLock::new();
    KEYS.get_or_init(|| {
        let dir = setup_dir();
        Keys {
            request_prover: RequestProver::load(&dir).unwrap(),
            request_verifier: RequestVerifier::load(&dir).unwrap(),
            withdrawal_prover: WithdrawalProver::load(&dir).unwrap(),
            withdrawal_verifier: WithdrawalVerifier::load(&dir).unwrap(),
            insertion: INSERTION_SIZES
                .iter()
                .map(|size| {
                    (
                        InsertionProver::load(&dir, *size).unwrap(),
                        InsertionVerifier::load(&dir, *size).unwrap(),
                    )
                })
                .collect(),
        }
    })
}

/// Prove an insertion statement with the prover of its size and check the
/// proof verifies.
fn prove_insertion(circuit: &InsertionCircuit) -> Groth16ProofWire {
    let (prover, verifier) = keys().insertion(circuit.public.size());
    let proof = prover.prove(&circuit.public, &circuit.witness).unwrap();
    assert!(verifier.verify(&circuit.public, &proof).unwrap());
    proof
}

/// The text of Solidity function `name` in `source`, up to the next function.
fn solidity_function<'a>(source: &'a str, name: &str) -> &'a str {
    let start = source
        .find(&format!("function {name}("))
        .unwrap_or_else(|| panic!("no function {name}"));
    let rest = &source[start + 1..];
    &source[start..start + 1 + rest.find("function ").unwrap_or(rest.len())]
}

fn read(file: &str) -> Vec<u8> {
    std::fs::read(setup_dir().join(file)).unwrap()
}

fn mutated(inputs: &[Felt252], index: usize) -> Vec<Felt252> {
    let mut inputs = inputs.to_vec();
    let value = core::felt_to_field(&inputs[index]) + Fr::ONE;
    inputs[index] = core::field_to_felt(&value);
    inputs
}

